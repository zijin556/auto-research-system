def _anchor_format(level: str) -> str:
    question, criterion, assumptions, scope, nongoals = _ANCHOR_SLOTS[level]
    return "\n".join([
        "锚点草稿块的格式（5 个标题照抄，每项都要写）：",
        "```锚点草稿",
        f"## {question}", "……",
        f"## {criterion}", "……",
        f"## {assumptions}",
        "| 编号 | 内容 | 依据 | 失效条件 | 状态 | 来源 |",
        "|---|---|---|---|---|---|",
        "| H1 | …… | …… | …… | 待批 | |",
        f"## {scope}", "……",
        f"## {nongoals}", "……",
        "```",
        r"假设表一行一条，编号 H1、H2……；「状态」一律写 待批，「来源」留空，由系统填写。表格里要写竖线时写成 \|。",
    ])


