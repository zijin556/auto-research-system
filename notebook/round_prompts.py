def _plain(value) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, Mapping):
        return json.dumps(dict(value), ensure_ascii=False, indent=2, default=str) if value else ""
    if isinstance(value, (list, tuple)):
        return "\n".join(text for text in (_plain(item).strip("\n") for item in value) if text.strip())
    return str(value)


def _render(value) -> str:
    """Material text for one marker: normalized newlines, outer blank lines dropped."""
    lines = _plain(value).replace("\r\n", "\n").replace("\r", "\n").split("\n")
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return "\n".join(lines).rstrip() or EMPTY


def markers(key: str) -> list[str]:
    """Marker names a template uses, in order of first appearance."""
    seen: list[str] = []
    for name in _MARKER.findall(_template(key)["text"]):
        if name not in seen:
            seen.append(name)
    return seen


def _template(key):
    try:
        return TEMPLATES[key]
    except (KeyError, TypeError):
        raise ValueError(f"未知的提示词模板：{key}") from None


def build(key: str, ctx: Mapping | None = None) -> str:
    """Fill one template. Missing or empty context values become （无）."""
    template = _template(key)
    ctx = ctx or {}
    body = _MARKER.sub(lambda m: _render(ctx.get(m.group(1))), template["text"])
    parts = [f"【模板】{key}", body]
    parts.extend(FORMATS[name] for name in template.get("formats", ()))
    if template.get("reply_format", True):
        parts.append(REPLY_FORMAT)
    return "\n\n".join(parts) + "\n"
