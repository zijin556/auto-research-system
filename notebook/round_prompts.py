def _compose(intro, materials, body, *, before="", after="", unseen=_UNSEEN, guard=_GUARD):
    """Role line, what the model sees (built from the slots), the slots, then the task."""
    labels = "、".join(label for label, _ in materials)
    sees = f"{before}你能看到的只有本提示词里的这些材料：{labels}{after}。"
    slots = "\n".join(f"【{label}】\n<<{name}>>" for label, name in materials)
    return f"{intro}\n{sees}{unseen}{guard}\n\n{slots}\n\n{body.strip()}"


def _t(title, role, intro, materials, body, *, formats=(), reply_format=True, web_search=False, **compose):
    entry = {"title": title, "role": role, "text": _compose(intro, materials, body, **compose)}
    if formats:
        entry["formats"] = tuple(formats)
    if not reply_format:
        entry["reply_format"] = False
    if web_search:
        entry["web_search"] = True
    return entry


